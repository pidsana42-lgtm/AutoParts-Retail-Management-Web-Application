func TestUpdateReturn_ApprovalUsesDedicatedOperation(t *testing.T) {
	for _, alreadyApproved := range []bool{false, true} {
		name := "pending"
		if alreadyApproved {
			name = "already_approved_is_idempotent"
		}
		t.Run(name, func(t *testing.T) {
			repo := newMockReturnRepo(t)
			approvedAt := time.Date(2026, 9, 7, 10, 0, 0, 0, time.UTC)
			wantApprover := uint(42)
			if alreadyApproved {
				wantApprover = 7 // A different user approved the existing record.
			}
			actor := wantApprover
			existing := entity.SalesReturn{Model: gorm.Model{ID: 81}, Status: enum.ReturnPending, Reason: "ผิดรุ่น"}
			approved := existing
			approved.Status, approved.ApprovedBy, approved.ApprovedAt = enum.ReturnApproved, &actor, &approvedAt
			if alreadyApproved {
				existing = approved
			}
			repo.getReturnFn = func(id uint) (*entity.SalesReturn, error) {
				if id != 81 {
					t.Fatalf("id = %d, want 81", id)
				}
				if repo.called["GetReturnByID"] == 1 {
					return &existing, nil
				}
				if !alreadyApproved && repo.called["ApproveReturn"] != 1 {
					t.Fatal("approval must occur before refetch")
				}
				if alreadyApproved {
					return &existing, nil
				}
				return &approved, nil
			}
			if !alreadyApproved {
				repo.approveReturnFn = func(id, approvedBy uint) error {
					if id != 81 || approvedBy != 42 {
						t.Errorf("ApproveReturn(%d, %d), want (81, 42)", id, approvedBy)
					}
					return nil
				}
			}
			forgedActor := uint(999)
			got, err := returnService.NewReturnService(repo).UpdateReturn(81, returnDTO.UpdateReturnDTO{
				Status: " approved ", ApprovedBy: &forgedActor,
			}, 42)
			if err != nil || got == nil {
				t.Fatalf("UpdateReturn() = %+v, %v", got, err)
			}
			if got.Status != enum.ReturnApproved || got.ApprovedBy == nil || *got.ApprovedBy != wantApprover || got.ApprovedAt == nil || !got.ApprovedAt.Equal(approvedAt) {
				t.Errorf("expected persisted approval metadata: %+v", got)
			}
			if alreadyApproved && (existing.ApprovedBy == nil || *existing.ApprovedBy != 7 || existing.ApprovedAt == nil || !existing.ApprovedAt.Equal(approvedAt)) {
				t.Errorf("repeat approval changed the original attribution: %+v", existing)
			}
			if repo.called["GetReturnByID"] != 2 {
				t.Errorf("expected original and persisted reads: %v", repo.called)
			}
		})
	}
}


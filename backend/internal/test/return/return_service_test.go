func TestCreateReturn_ApprovalUsesAuthenticatedRole(t *testing.T) {
	for _, tc := range []struct {
		name string
		role string
		want enum.ReturnStatus
	}{
		{"owner", "OWNER", enum.ReturnApproved},
		{"admin", "ADMIN", enum.ReturnApproved},
		{"normalized_owner", " owner \t", enum.ReturnApproved},
		{"normalized_admin", " admin ", enum.ReturnApproved},
		{"employee", "EMPLOYEE", enum.ReturnPending},
		{"unknown_role", "CUSTOMER", enum.ReturnPending},
		{"missing_role", "", enum.ReturnPending},
	} {
		t.Run(tc.name, func(t *testing.T) {
			repo := newMockReturnRepo(t)
			forgedActor := uint(999)
			forgedTime := time.Date(2000, 1, 1, 0, 0, 0, 0, time.UTC)
			input := returnDTO.CreateReturnDTO{
				OriginalOrderID: 12, Reason: "สินค้าผิดรุ่น", RefundMethod: "CASH",
				CreatedBy: forgedActor, Status: "REFUNDED", ApprovedBy: &forgedActor, ApprovedAt: &forgedTime,
				Items: []returnDTO.CreateReturnItemInputDTO{{ProductID: 3, Quantity: 2, UnitPrice: 100}},
			}
			var saved entity.SalesReturn
			before := time.Now()
			repo.createReturnFn = func(ret *entity.SalesReturn, items []entity.SalesReturnItem) error {
				if ret.Status != tc.want || ret.CreatedBy != 42 {
					t.Fatalf("status/creator = %s/%d, want %s/42", ret.Status, ret.CreatedBy, tc.want)
				}
				if tc.want == enum.ReturnApproved {
					if ret.ApprovedBy == nil || *ret.ApprovedBy != 42 || ret.ApprovedAt == nil {
						t.Fatalf("approval must use the authenticated actor: %+v", ret)
					}
					if ret.ApprovedAt.Before(before) || ret.ApprovedAt.After(time.Now()) {
						t.Errorf("approval time must be generated by the server: %v", ret.ApprovedAt)
					}
				} else if ret.ApprovedBy != nil || ret.ApprovedAt != nil {
					t.Errorf("pending return retained forged approval metadata: %+v", ret)
				}
				ret.ID, ret.ReturnNumber = 81, "RTN-2026-00081"
				ret.SalesReturnItems = items
				saved = *ret
				return nil
			}
			repo.getReturnFn = func(id uint) (*entity.SalesReturn, error) {
				if id != 81 || repo.called["CreateReturn"] != 1 {
					t.Fatalf("must fetch the newly created return, id = %d, calls = %v", id, repo.called)
				}
				return &saved, nil
			}
			got, err := returnService.NewReturnService(repo).CreateReturn(input, 42, tc.role)
			if err != nil || got == nil {
				t.Fatalf("CreateReturn() = %+v, %v", got, err)
			}
			if got.ID != 81 || got.ReturnNumber != "RTN-2026-00081" || got.Status != tc.want || got.CreatedBy != 42 {
				t.Errorf("unexpected created response: %+v", got)
			}
		})
	}
}

func TestCreateReturn_ItemsAndRefundAmount(t *testing.T) {
	items := []returnDTO.CreateReturnItemInputDTO{
		{ProductID: 3, Quantity: 2, UnitPrice: 150.25},
		{ProductID: 4, Quantity: 1, UnitPrice: 99.5},
	}
	for _, tc := range []struct {
		name       string
		legacy     bool
		amount     float64
		wantAmount float64
	}{
		{"canonical_items_calculate_total", false, 0, 400},
		{"legacy_items_calculate_total", true, 0, 400},
		{"explicit_partial_refund", false, 120, 120},
	} {
		t.Run(tc.name, func(t *testing.T) {
			repo := newMockReturnRepo(t)
			returnDate := time.Date(2026, 9, 6, 9, 0, 0, 0, time.UTC)
			requestedAt := returnDate.Add(time.Hour)
			input := returnDTO.CreateReturnDTO{
				ReturnNumber: "RTN-2026-00082", OriginalOrderID: 12, Reason: "ผิดรุ่น", Note: "กล่องยังไม่แกะ",
				RefundMethod: "TRANSFER", RefundAmount: tc.amount, ReturnDate: &returnDate, RequestedAt: &requestedAt,
			}
			if tc.legacy {
				input.Items = items
			} else {
				input.SalesReturnItems = items
				// The canonical field wins when both supported input names are present.
				input.Items = []returnDTO.CreateReturnItemInputDTO{{ProductID: 999, Quantity: 1, UnitPrice: 999}}
			}
			var saved entity.SalesReturn
			repo.createReturnFn = func(ret *entity.SalesReturn, gotItems []entity.SalesReturnItem) error {
				wantItems := []entity.SalesReturnItem{
					{ProductID: 3, Quantity: 2, UnitPrice: 150.25, Subtotal: 300.5},
					{ProductID: 4, Quantity: 1, UnitPrice: 99.5, Subtotal: 99.5},
				}
				if !reflect.DeepEqual(gotItems, wantItems) {
					t.Errorf("items = %+v, want %+v", gotItems, wantItems)
				}
				if ret.RefundAmount != tc.wantAmount || ret.OriginalOrderID != 12 || ret.RefundMethod != "TRANSFER" ||
					ret.Reason != input.Reason || ret.Note != input.Note || ret.ReturnNumber != input.ReturnNumber ||
					!ret.ReturnDate.Equal(returnDate) || !ret.RequestedAt.Equal(requestedAt) {
					t.Errorf("incorrect return fields: %+v", ret)
				}
				ret.ID, ret.SalesReturnItems = 82, gotItems
				saved = *ret
				return nil
			}
			repo.getReturnFn = func(id uint) (*entity.SalesReturn, error) { return &saved, nil }
			got, err := returnService.NewReturnService(repo).CreateReturn(input, 42, "EMPLOYEE")
			if err != nil || got == nil {
				t.Fatalf("CreateReturn() = %+v, %v", got, err)
			}
			if got.RefundAmount != tc.wantAmount || len(got.SalesReturnItems) != 2 {
				t.Errorf("incorrect refund response: %+v", got)
			}
		})
	}
}

